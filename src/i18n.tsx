type Vars = Record<string, string | number>;
interface I18n { lang: Lang; t(k: Key, v?: Vars): string; toggle(): void }
const Ctx = createContext<I18n>(null!);
export const useI18n = () => useContext(Ctx);

const initial = (): Lang => (localStorage.getItem("att.lang") as Lang | null) ?? (navigator.language.startsWith("ar") ? "ar" : "en");

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initial);
  useEffect(() => { document.documentElement.lang = lang; document.documentElement.dir = lang === "ar" ? "rtl" : "ltr"; localStorage.setItem("att.lang", lang); }, [lang]);
  const t = useCallback((k: Key, v?: Vars) => (lang === "ar" ? ar : en)[k].replace(/\{(\w+)\}/g, (_, n) => String(v?.[n] ?? "")), [lang]);
  const value = useMemo(() => ({ lang, t, toggle: () => setLang((l) => (l === "ar" ? "en" : "ar")) }), [lang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}
